#!/usr/bin/env node
// Copies what the app shares with the prototype, so there is one source of truth:
//
//   node scripts/sync-shared.mjs
//
// 1. src/shared/companion.generated.js  <- prototype/src/00-data.js, 01-evidence.generated.js, 10-domain.js
//    (the tested domain logic: evidence gate, health rating, split review,
//    readiness, barcode and GS1 parsing, and the evidence library itself)
// 2. src/theme/tokens.generated.ts      <- design/generated/theme.ts
// 3. src/theme/palettes.generated.ts    <- design/app-palettes.json
//
// Run it after `node prototype/build.mjs` whenever the prototype's logic, the
// evidence library or the design tokens change. CI fails if the copies are stale
// (`node scripts/sync-shared.mjs --check`).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const repo = join(app, '..', '..'); // nutrition-training-companion/
const read = (p) => readFileSync(join(repo, p), 'utf8');
const check = process.argv.includes('--check');
let stale = 0;
const write = (rel, text) => {
  const file = join(app, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
      console.error(`stale: ${rel}`);
      stale++;
    }
    return;
  }
  writeFileSync(file, text);
  console.log(`wrote ${rel} (${Math.round(text.length / 1024)} KB)`);
};

const SOURCES = ['prototype/src/00-data.js', 'prototype/src/01-evidence.generated.js', 'prototype/src/10-domain.js'];
const shared = `/* Generated by scripts/sync-shared.mjs from ${SOURCES.join(', ')}.
   Do not edit: change the prototype, rebuild it, then run the script.
   The prototype files attach themselves to window.Companion; here they attach
   to a private object instead, which this module exports. */
/* eslint-disable */
const window = { Companion: {} };

${SOURCES.map((s) => `/* ---- ${s} ---- */\n${read(s)}`).join('\n')}

const C = window.Companion;
export const data = C.data;
export const domain = C.domain;
`;
write('src/shared/companion.generated.js', shared);

write('src/theme/tokens.generated.ts', `/* Copied from design/generated/theme.ts by scripts/sync-shared.mjs. Do not edit. */\n${read('design/generated/theme.ts')}`);

const palettes = JSON.parse(read('design/app-palettes.json'));
delete palettes.$comment;
write('src/theme/palettes.generated.ts', `/* Generated from design/app-palettes.json by scripts/sync-shared.mjs. Do not edit. */
import type { ColorToken } from './tokens.generated';

export type PaletteEntry = { bg: ColorToken; fg: ColorToken; label: string };
export const palettes: Record<string, Record<string, PaletteEntry>> = ${JSON.stringify(palettes, null, 2)};
`);

if (check && stale) {
  console.error(`${stale} generated file(s) are stale. Run: node scripts/sync-shared.mjs`);
  process.exit(1);
}
